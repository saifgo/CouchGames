/**
 * Regenerates vectors/golden.json from test/cases.ts.
 * Only run this on an intentional protocol change (and bump PROTOCOL_VERSION).
 * The Kotlin host's unit tests read the same file.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { PROTOCOL_VERSION } from '../src/constants.js';
import { encodeControl, encodeEchoInto, encodeInputInto, toHex } from '../src/codec.js';
import { controlCases, echoCases, inputCases, invalidCases } from '../test/cases.js';

const scratch = new DataView(new ArrayBuffer(64));
const slice = (n: number) => new Uint8Array(scratch.buffer, 0, n);

const vectors = {
  protocolVersion: PROTOCOL_VERSION,
  note: 'Generated by packages/protocol/scripts/generate-vectors.ts. Do not edit by hand.',
  input: inputCases.map((c) => ({ name: c.name, hex: toHex(slice(encodeInputInto(c.value, scratch))), value: c.value })),
  echo: echoCases.map((c) => ({ name: c.name, hex: toHex(slice(encodeEchoInto(c.value, scratch))), value: c.value })),
  control: controlCases.map((c) => ({ name: c.name, hex: toHex(encodeControl(c.value)), value: c.value })),
  invalid: invalidCases,
};

const out = fileURLToPath(new URL('../vectors/golden.json', import.meta.url));
writeFileSync(out, JSON.stringify(vectors, null, 2) + '\n');
console.log(`wrote ${out}`);
