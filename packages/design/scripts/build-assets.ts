/**
 * Writes every logo file from the one mark geometry in src/mark.ts:
 *
 *   packages/design/assets/       mark SVGs, lockup + banner + icon PNGs (for docs, stores, press)
 *   apps/host-web/public/         favicon.svg, icon-192/512.png, apple-touch-icon.png
 *   apps/controller-web/public/   icon.svg, icon-192/512.png, apple-touch-icon.png
 *   apps/host-android-tv/…/res/   launcher foreground, logo vectors, TV banner PNG
 *
 * PNGs with the wordmark are rendered in headless Chromium with the bundled Fredoka.
 *
 *   pnpm --filter @couch/design assets
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';
import { COLORS, MARK_ON, TAGLINE, markSvg, markVectorPaths, type MarkColors, type Variant, DRAWINGS } from '../src/index.js';

const pkg = join(dirname(fileURLToPath(import.meta.url)), '..');
const root = join(pkg, '../..');
const out = (p: string) => join(root, p);
const assets = join(pkg, 'assets');
const res = out('apps/host-android-tv/app/src/main/res');
const hostPublic = out('apps/host-web/public');
const ctrlPublic = out('apps/controller-web/public');
for (const d of [assets, `${res}/drawable`, `${res}/drawable-xhdpi`, `${res}/values`]) mkdirSync(d, { recursive: true });

const write = (path: string, text: string) => {
  writeFileSync(path, text);
  console.log('✓', path.slice(root.length + 1));
};

// ---- Mark SVGs --------------------------------------------------------------------------------
const marks: Record<string, [Variant, MarkColors]> = {
  'mark.svg': ['full', MARK_ON.cream],
  'mark-on-yellow.svg': ['cut', MARK_ON.yellow],
  'mark-on-ink.svg': ['cut', MARK_ON.ink],
  'mark-mini.svg': ['mini', MARK_ON.cream],
  'mark-mono.svg': ['full', MARK_ON.mono],
  'mark-mono-reversed.svg': ['full', MARK_ON.monoReversed],
};
for (const [name, [v, c]] of Object.entries(marks)) write(join(assets, name), markSvg(v, c) + '\n');

/** A square icon: rounded tile of `bg` with the mark centred at `fill` of the tile width. */
function iconSvg(size: number, radius: number, bg: string, v: Variant, c: MarkColors, fill: number): string {
  const [vx, vy, vw, vh] = DRAWINGS[v].viewBox;
  const w = size * fill;
  const h = (w * vh) / vw;
  const inner = markSvg(v, c, `x="${(size - w) / 2}" y="${(size - h) / 2}" width="${w}" height="${h}"`).replace(` xmlns="http://www.w3.org/2000/svg"`, '');
  void vx, vy;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}"><rect width="${size}" height="${size}" rx="${radius}" fill="${bg}"/>${inner}</svg>\n`;
}

// Favicon: simplified mark, mono Yellow on Ink (brand kit board 06).
const favicon = iconSvg(32, 8, COLORS.ink, 'mini', { y: COLORS.ink, i: COLORS.yellow, p: COLORS.ink }, 0.82);
// App icon: Yellow tile, die-cut mark with an Ink border.
const appIcon = iconSvg(512, 122, COLORS.yellow, 'cut', MARK_ON.yellow, 0.78);
write(join(assets, 'favicon.svg'), favicon);
write(join(assets, 'app-icon.svg'), appIcon);
write(join(hostPublic, 'favicon.svg'), favicon);
write(join(ctrlPublic, 'favicon.svg'), favicon);
write(join(ctrlPublic, 'icon.svg'), appIcon);

// ---- Android ---------------------------------------------------------------------------------
const vector = (w: number, h: number, body: string) =>
  `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by packages/design/scripts/build-assets.ts. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${w}dp" android:height="${h}dp" android:viewportWidth="${w}" android:viewportHeight="${h}">
${body}
</vector>
`;
{
  // Adaptive icon foreground: 108 dp canvas, mark inside the 72 dp safe zone (18 dp inset).
  const [, , vw, vh] = DRAWINGS.cut.viewBox;
  const w = 66;
  const k = w / vw;
  const h = vh * k;
  write(`${res}/drawable/ic_launcher_foreground.xml`, vector(108, 108, markVectorPaths('cut', MARK_ON.yellow, k, (108 - w) / 2, (108 - h) / 2)));
  // In-app logo marks (Compose: painterResource). Size set by the caller.
  for (const [name, v, c] of [
    ['cp_mark_on_ink', 'cut', MARK_ON.ink],
    ['cp_mark', 'full', MARK_ON.cream],
  ] as const) {
    const [, , vw2, vh2] = DRAWINGS[v].viewBox;
    write(`${res}/drawable/${name}.xml`, vector(vw2, vh2, markVectorPaths(v, c, 1, 0, 0)));
  }
}

// ---- PNGs (wordmark needs the font) ------------------------------------------------------------
const fontCss = `@font-face{font-family:Fredoka;font-weight:300 700;src:url(data:font/woff2;base64,${readFileSync(join(pkg, 'fonts/fredoka-latin.woff2')).toString('base64')}) format('woff2')}
@font-face{font-family:Inter;font-weight:100 900;src:url(data:font/woff2;base64,${readFileSync(join(pkg, 'fonts/inter-latin.woff2')).toString('base64')}) format('woff2')}
*{margin:0;box-sizing:border-box}body{background:transparent}
.wm{font-family:Fredoka;font-weight:700;letter-spacing:-0.01em;line-height:1}`;

/** 320×180 Android TV banner (variant 2: Yellow ground, Ink die-cut), drawn at scale s. */
const banner = (s: number) => `<div id="x" style="width:${320 * s}px;height:${180 * s}px;background:${COLORS.yellow};display:flex;align-items:center;gap:${17 * s}px;padding:0 ${30 * s}px;color:${COLORS.ink}">
  ${markSvg('cut', MARK_ON.yellow, `width="${112 * s}" height="${(112 * s * 120) / 156}"`)}
  <div style="display:flex;flex-direction:column;gap:${4 * s}px"><div class="wm" style="font-size:${40 * s}px">CouchPad</div>
  <div style="font:500 ${12.5 * s}px/1 Inter;opacity:.8">${TAGLINE}</div></div></div>`;
const lockup = (bg: string, ink: string, v: Variant, c: MarkColors, pad = false) => `<div id="x" style="display:inline-flex;align-items:center;gap:44px;padding:56px 72px;background:${bg};color:${ink}">
  ${markSvg(v, c, `width="300" height="${(300 * DRAWINGS[v].viewBox[3]) / DRAWINGS[v].viewBox[2]}"`)}
  <div class="wm" style="font-size:116px">${pad ? `Couch<span style="color:${COLORS.yellow}">Pad</span>` : 'CouchPad'}</div></div>`;
const tile = (size: number, svg: string) => `<div id="x" style="width:${size}px;height:${size}px">${svg.replace('<svg ', `<svg width="${size}" height="${size}" `)}</div>`;
const squareIcon = (size: number) => iconSvg(size, 0, COLORS.yellow, 'cut', MARK_ON.yellow, 0.74);

const pngs: [string, string][] = [
  [`${res}/drawable-xhdpi/banner.png`, banner(2)],
  [join(assets, 'banner-1280x720.png'), banner(4)],
  [join(assets, 'lockup-on-cream.png'), lockup(COLORS.cream, COLORS.ink, 'full', MARK_ON.cream)],
  [join(assets, 'lockup-on-ink.png'), lockup(COLORS.ink, COLORS.cream, 'cut', MARK_ON.ink, true)],
  [join(assets, 'lockup-on-yellow.png'), lockup(COLORS.yellow, COLORS.ink, 'cut', MARK_ON.yellow)],
  [join(assets, 'app-icon-512.png'), tile(512, appIcon)],
  // Store icon: square, the store rounds it.
  [join(assets, 'play-icon-512.png'), tile(512, squareIcon(512))],
  ...[hostPublic, ctrlPublic].flatMap((dir): [string, string][] => [
    [join(dir, 'icon-192.png'), tile(192, appIcon)],
    [join(dir, 'icon-512.png'), tile(512, appIcon)],
    // iOS rounds the corners itself: give it a full square.
    [join(dir, 'apple-touch-icon.png'), tile(180, squareIcon(180))],
  ]),
];
const browser = await chromium.launch();
const page = await browser.newPage({ deviceScaleFactor: 1 });
for (const [path, html] of pngs) {
  await page.setContent(`<html><head><style>${fontCss}</style></head><body>${html}</body></html>`);
  await page.evaluate(() => document.fonts.ready);
  await page.locator('#x').screenshot({ path, omitBackground: true });
  console.log('✓', path.slice(root.length + 1));
}
await browser.close();
